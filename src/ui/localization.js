const EXCLUDED =
  "#editor,#readerContent,#readerTitle,#readerEmoji,#readerDrawingDescriptionText,.workspace-results,.page-preview-title,.page-preview-snippet,.recovery-page strong,pre,textarea,input,.shared-link-row strong,.export-note-content";
export function translateInterface(text, language) {
  if (language !== "ru") return text;
  if (RU[text]) return RU[text];
  let match;
  if (
    (match = text.match(
      /^(.+) · (Published copy|Creation needs confirmation|Disabled|Unknown)$/,
    ))
  )
    return (
      match[1] +
      " · " +
      {
        "Published copy": "Опубликованная копия",
        "Creation needs confirmation": "Создание требует подтверждения",
        Disabled: "Отключена",
        Unknown: "Неизвестно",
      }[match[2]]
    );
  if ((match = text.match(/^Published (.+)$/)))
    return "Опубликовано " + match[1];
  if (text.startsWith("Stored only in this browser on this device"))
    return text
      .replace(
        "Stored only in this browser on this device",
        "Хранится только в этом браузере на этом устройстве",
      )
      .replace("currently used", "занято")
      .replace("Last backup:", "Последняя копия:")
      .replace(
        "Keep a portable backup outside this browser.",
        "Храните резервную копию вне этого браузера.",
      );
  if ((match = text.match(/^(\d+) words · (\d+) chars$/)))
    return match[1] + " слов · " + match[2] + " символов";
  if ((match = text.match(/^(\d+) pages(.*)$/)))
    return match[1] + " страниц" + (match[2] ? " · показаны первые 100" : "");
  if ((match = text.match(/^Brush size: (.+)$/)))
    return "Толщина кисти: " + match[1];
  if ((match = text.match(/^Use (.+) theme$/)))
    return "Использовать тему " + match[1];
  if ((match = text.match(/^Use drawing colour (.+)$/)))
    return "Использовать цвет " + match[1];
  if ((match = text.match(/^Save failed: (.+)$/)))
    return "Не удалось сохранить: " + match[1];
  if (
    (match = text.match(
      /^Preview captured (.+)\. Creating a short link captures the selected copy at that moment\.$/,
    ))
  )
    return (
      "Предпросмотр создан " +
      match[1] +
      ". Короткая ссылка сохранит выбранную копию в момент создания."
    );
  if (
    (match = text.match(
      /^(Marker|Pressure pen|Select strokes) \(click to switch to brush\)$/,
    ))
  )
    return (
      {
        Marker: "Маркер",
        "Pressure pen": "Перо с нажимом",
        "Select strokes": "Выделение штрихов",
      }[match[1]] + " (нажмите для выбора кисти)"
    );
  if (
    (match = text.match(
      /^(\d+) link controls restored\. No copies were uploaded or changed\.$/,
    ))
  )
    return (
      "Восстановлено ключей: " +
      match[1] +
      ". Копии не загружались и не менялись."
    );
  return text;
}

export function setupLocalization() {
  let language = "en";
  try {
    language =
      localStorage.getItem("blackboard-text:language") === "ru" ? "ru" : "en";
  } catch {
    /* Optional preference. */
  }
  const originals = new WeakMap(),
    attributes = new WeakMap();
  function excluded(node) {
    return node.parentElement?.closest(EXCLUDED);
  }
  function visit(root) {
    const elements = [root],
      walker = document.createTreeWalker(
        root,
        NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT,
        {
          acceptNode(node) {
            if (node instanceof Element && node.matches(EXCLUDED))
              return NodeFilter.FILTER_REJECT;
            return NodeFilter.FILTER_ACCEPT;
          },
        },
      );
    let node = walker.nextNode();
    while (node) {
      if (node instanceof Element) elements.push(node);
      else if (!excluded(node)) {
        const current = node.textContent,
          known = originals.get(node),
          source = known && current === known.result ? known.source : current;
        const trimmed = source.trim(),
          result = trimmed
            ? source.replace(trimmed, translateInterface(trimmed, language))
            : source;
        originals.set(node, { source, result });
        if (current !== result) node.textContent = result;
      }
      node = walker.nextNode();
    }
    for (const el of elements) {
      if (
        !(el instanceof Element) ||
        el.closest(
          "#editor,#readerContent,#readerTitle,#readerDrawingDescriptionText,[role=img],.workspace-results,.export-note-content",
        )
      )
        continue;
      const saved = attributes.get(el) || {};
      for (const name of ["title", "aria-label", "placeholder"]) {
        const value = el.getAttribute(name);
        if (value === null) continue;
        const prior = saved[name],
          source = prior && value === prior.result ? prior.source : value,
          result = translateInterface(source, language);
        saved[name] = { source, result };
        if (result !== value) el.setAttribute(name, result);
      }
      attributes.set(el, saved);
    }
  }
  const row = document.createElement("label");
  row.className = "settings-language";
  const name = document.createElement("span");
  name.textContent = "Interface language";
  const select = document.createElement("select");
  select.id = "interfaceLanguage";
  select.setAttribute("aria-label", "Interface language");
  select.innerHTML =
    '<option value="en">English</option><option value="ru">Русский</option>';
  select.value = language;
  row.append(name, select);
  document.querySelector(".controls-panel-body")?.append(row);
  const apply = () => {
    document.documentElement.lang = language;
    document.documentElement.style.setProperty(
      "--editor-placeholder",
      language === "ru" ? "'Начните писать…'" : "'Start writing...'",
    );
    visit(document.body);
  };
  select.addEventListener("change", () => {
    language = select.value;
    try {
      localStorage.setItem("blackboard-text:language", language);
    } catch {
      /* Optional preference. */
    }
    apply();
  });
  let queued = false;
  new MutationObserver(() => {
    if (queued) return;
    queued = true;
    queueMicrotask(() => {
      queued = false;
      visit(document.body);
    });
  }).observe(document.body, {
    subtree: true,
    childList: true,
    characterData: true,
    attributes: true,
    attributeFilter: ["title", "aria-label", "placeholder"],
  });
  apply();
}
